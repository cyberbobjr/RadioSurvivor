-- Text entry drawn on the paper: underlined (Say line) or a light box (private note). Ink text colour is set on the
-- Java object, after addChild (base ui-windows.md, ISTextEntryBox).
local function paperEntry(entry, underline)
    entry.prerender = function(e)
        if underline then
            local c = COLOR.rust
            local a = (e.javaObject and e:isEditable()) and 1 or 0.35
            e:drawRect(0, e.height - 2, e.width, 2, a, c[1], c[2], c[3])
        else
            local p, f = COLOR.paperLight, COLOR.frame
            e:drawRect(0, 0, e.width, e.height, 0.85, p[1], p[2], p[3])
            e:drawRectBorder(0, 0, e.width, e.height, 1, f[1], f[2], f[3])
        end
    end
    local i = COLOR.ink
    entry:setTextRGBA(i[1], i[2], i[3], 1)
end

local function drawDot(element, x, y, size, c)
    local tex = texture('dot')
    if tex then element:drawTextureScaled(tex, x, y, size, size, 1, c[1], c[2], c[3])
    else element:drawRect(x, y, size, size, 1, c[1], c[2], c[3]) end
end

-- Radio this character talks into from the notebook: an equipped two-way radio (hand, back), else a two-way radio
-- carried in the main inventory (belt), else the equipped one (its problem is shown). Talk.problem judges it.
local function talkDevice(player)
    if not player then return nil end
    local equipped = player:getEquipedRadio()
    local data = equipped and equipped:getDeviceData()
    if data and data:getIsTwoWay() then return equipped end
    local inventory = player:getInventory()
    local items = inventory and inventory:getItems()
    if items then
        for i = 0, items:size() - 1 do
            local item = items:get(i)
            if instanceof(item, 'Radio') then
                local d = item:getDeviceData()
                if d and d:getIsTwoWay() then return item end
            end
        end
    end
    return equipped
end

