    self.deliver = stamp(self, tr('Deliver'), function(w) if w.row then w:openDelivery(w.row) end end)
    self.claim = stamp(self, tr('Claim'), function(w) w:request('claim') end)
    -- E11-T13: report of a met objective to the requester, next to them (the way without the bridge).
    self.report = stamp(self, tr('ReportButton'), function(w) w:request('report') end)
    self.abandon = stamp(self, tr('Abandon'), function(w)
        local row = w.row
        w:confirm(tr('ConfirmAbandon'), function() w:request('abandon', row) end)
    end)
    self.invite = stamp(self, tr('Invite'), function(w)
        local target = w.inviteTargets[w.inviteChoice.selected]
        if target then w:request('invite', nil, {character = target.id}) end
    end)
    self.inviteChoice = ISComboBox:new(0, 0, 100, fontHeight() + 14, self, nil)
    self.inviteChoice:initialise(); self:addChild(self.inviteChoice)
    -- Team tab (E09-T03): the server checks again that the sender is the current owner of the faction.
    self.grant = stamp(self, tr('MandateGrant'), function(w)
        if w.row then Client.send('mandate', {member = w.row.id, action = 'grant'}) end
    end)
    self.revoke = stamp(self, tr('MandateRevoke'), function(w)
        if w.row then Client.send('mandate', {member = w.row.id, action = 'revoke'}) end
    end)
    -- E04-T14 (Q17): read-only view of every character's reputation, administrators only (checked by the server).
    self.repAdmin = stamp(self, tr('RepAdminButton'), function() Client.send('rep_admin') end)
    self.actions = {self.saveNote, self.talk, self.clearTarget, self.accept, self.deliver, self.report, self.claim,
        self.abandon, self.invite, self.grant, self.revoke, self.repAdmin}
    -- Radio tab: "Tune my radio" under the frequency list, "Say:" line and "Transmit" under the conversation.
    self.tune = stamp(self, tr('RadioTune'), function(w) if w.row then History.tune(w.row.khz) end end)
    self.say = ISTextEntryBox:new('', 0, 0, 100, fontHeight(UIFont.Medium) + 10)
    self.say.font = UIFont.Medium
    self.say:initialise(); self:addChild(self.say)
    self.say:setMaxTextLength(Const.MAX_INPUT_CHARS)
    paperEntry(self.say, true)
    self.say:setPlaceholderTextRGBA(0.55, 0.51, 0.43, 1)
    self.say.onCommandEntered = function() window:sendSay() end
    self.say.onOtherKey = function(_, key) if key == KEY_ESCAPE then window:releaseFocus() end end
    self.sendRadio = stamp(self, getText('IGUI_RadioSurvivor_Send'), function(w) w:sendSay() end, true)
    self.sayEditable = true
    -- Contacts tab (E17-T06): "Say:" line to the selected NPC, in solo (no chat) and MP. Client.talk sends the same
    -- 'talk' command as the local chat: same server checks and same npc_talk request.
    self.speak = ISTextEntryBox:new('', 0, 0, 100, fontHeight(UIFont.Medium) + 10)
    self.speak.font = UIFont.Medium
    self.speak:initialise(); self:addChild(self.speak)
    self.speak:setMaxTextLength(Const.MAX_INPUT_CHARS)
    paperEntry(self.speak, true)
    self.speak:setPlaceholderTextRGBA(0.55, 0.51, 0.43, 1)
    self.speak.onCommandEntered = function() window:sendTalk() end
    self.speak.onOtherKey = function(_, key) if key == KEY_ESCAPE then window:releaseFocus() end end
    self.speakSend = stamp(self, tr('TalkSend'), function(w) w:sendTalk() end, true)
    self.speakEditable = true
    self:refresh()
end

-- Confirmation dialog, created without being shown (vanilla ISModalDialog: sized to its text, centred on the mouse and
-- kept on screen). Read by the in-game suite rs.notebook.visual, which measures it before showing it.
function Notebook.newConfirm(text, callback)
    local modal = ISModalDialog:new(0, 0, math.min(540, getCore():getScreenWidth() - 60), 220, text, true, nil,
        function(_, b) if b.internal == 'YES' then callback() end end, 0)
    modal:initialise()
    return modal
end

function Notebook:confirm(text, callback)
    local modal = Notebook.newConfirm(text, callback)
    modal:addToUIManager()
    return modal
end

function Notebook:request(command, row, extra)
    row = row or self.row
    if not row then return end
    local args = extra or {}
    args.mission, args.revision = row.id, row.revision
    Client.send(command, args)
end

-- Keyboard focus back to the game (an ISTextEntryBox keeps it until unfocus or the next left click, even hidden).
-- Without argument: every text entry of the notebook; otherwise only the entries given.
function Notebook:releaseFocus(...)
    local entries = {...}
    if #entries == 0 then entries = {self.say, self.speak, self.note} end
    for _, entry in ipairs(entries) do
        if entry and entry.javaObject and entry:isFocused() then entry:unfocus() end
    end
end

function Notebook:close()
    self:releaseFocus()
    ISCollapsableWindow.close(self)
end

function Notebook:changeTab(name)
    self:releaseFocus()
    self.tab, self.selectedId = name, nil
    if name == 'Radio' then History.request() end
    self:refresh()
end

-- Is the player reading the Radio tab right now (visible, expanded)? With khz: this frequency, selected there.
-- Otherwise a new line lights the indicator (and the dot of its frequency).
function Notebook:viewingRadio(khz)
    if not (self.tab == 'Radio' and self:isVisible() and not self.isCollapsed) then return false end
    return khz == nil or (self.row ~= nil and self.row.khz == khz)
end

function Notebook:refresh()
    if not self.list then return end
    local old = self.selectedId
    self.list:clear()
    local team = Client.snapshot.team
    local rows = self.tab == 'Contacts' and Client.snapshot.contacts or self.tab == 'Missions' and Client.snapshot.missions
        or self.tab == 'Radio' and History.sorted() or self.tab == 'Team' and team and team.members or {}
    for i, row in ipairs(rows or {}) do
        local label = (self.tab == 'Contacts' or self.tab == 'Team') and row.name
            or self.tab == 'Radio' and tr('RadioFrequency', Const.frequencyLabel(row.khz))
            or getText(row.titleKey or 'IGUI_RS_FirstAid') .. ' - ' .. row.requester
        self.list:addItem(label, row)
        if row.id == old then self.list.selected = i end
    end
    if not old and rows[1] then self.selectedId, self.list.selected = rows[1].id, 1 end
    self:showDetail()
end

function Notebook:showDetail()
    local row
    for _, item in ipairs(self.list.items) do if item.item.id == self.selectedId then row = item.item end end
    self.row = row
    for _, b in ipairs(self.actions) do b:setVisible(false) end
    self.note:setVisible(false); self.inviteChoice:setVisible(false)
    local radio = self.tab == 'Radio'
    self.tune:setVisible(false)
    self.say:setVisible(radio); self.sendRadio:setVisible(radio)
    local talkLine = self.tab == 'Contacts' and row ~= nil and Client.snapshot.npcProvider == true
    self.speak:setVisible(talkLine); self.speakSend:setVisible(talkLine)
    self.detail.defaultFont = radio and UIFont.Medium or UIFont.Small
    local text = {}
    local function line(s) text[#text + 1] = clean(s) end
    -- Without an NPC engine the notebook has no interlocutor: said on the Contacts page only (Walt's radio works).
    if self.tab == 'Contacts' and not Client.snapshot.npcProvider then line(tr('NoNPCProvider')) end
    if Client.snapshot.storage == false then line(tr('Error_Storage')) end
    if self.tab == 'Contacts' and row then
        line(row.name)
        -- E17-T06: readable group name only (never the raw id), nothing without a group.
        if type(row.groupName) == 'string' and row.groupName ~= '' then line(tr('Group', row.groupName)) end
        line(tr('Style_' .. row.personality.style))
        line(tr('Traits', row.personality.courage, row.personality.sociability, row.personality.generosity))
        if row.background ~= '' then line(row.background) end
        -- E09-T07: relation of this NPC toward the reader's character, translated here.
        line(tr('RelTitle'))
        for _, s in ipairs(relationLines(row.relation)) do line(s) end
        line(row.alive and (row.near and tr('UseChat') or tr('JoinRequester')) or tr('Dead'))
        line(tr('KnownConversations'))
        for _, speech in ipairs(row.history or {}) do line(speech.author .. ' : ' .. speech.text) end
        self.talk:setVisible(true); enable(self.talk, row.alive and row.near)
        self.clearTarget:setVisible(true)
        self.note:setVisible(true); self.saveNote:setVisible(true)
        if self.noteNpc ~= row.id then self.note:setText(row.note or ''); self.noteNpc = row.id end
    elseif self.tab == 'Missions' and row then
        line(getText(row.titleKey)); line(tr('Requester', row.requester))
        -- E11-T13: objective met, the report to the requester is expected (in person, or on the voice's frequency).
        line(row.toReport and tr('State_toReport') or tr('State_' .. row.state))
        local scout = row.template == 'scout' -- E11-T03: reach a place, then report in person
        local retrieve = row.template == 'retrieve_id' -- E11-T05: bring back the ID card of a body
        local clear = row.template == 'clear' -- E11-T04: kill zombies inside the circle drawn on the map
        local recover = row.template == 'recover' -- E11-T06: carry the cache bag to the depot of the group
        local signal = row.template == 'signal' -- E11-T07: light a signal of a colour in the circle, at an hour
        -- E11-T08: mission given by a radio voice: no body to join, report on its frequency, information as reward.
        local voice = row.donor == 'voice'
        if scout or retrieve or clear or recover or signal then
            if row.placeKind and row.placeKind ~= '' then line(tr('ScoutPlace', placeName(row.placeKind))) end
            -- E11-T09: clues of the place, translated here (the server sends keys and codes only).
            local clues = {}
            for _, clue in ipairs(type(row.clues) == 'table' and row.clues or {}) do
                local said = clueText(clue)
                if said then clues[#clues + 1] = said end
            end
            if #clues > 0 then
                line(tr('ScoutClues'))
                for _, said in ipairs(clues) do line('- ' .. said) end
            end
        end
        if recover then
            if row.mapZone and not row.found then line(tr('RecoverMapZone')) end
            if row.cache and row.cache ~= '' then line(tr('RecoverCache', getText('IGUI_RS_Cache_' .. row.cache))) end
            line(row.found and tr('RecoverFound', row.foundBy) or tr('RecoverNotFound'))
            if row.depotZone then line(tr('RecoverDepotZone')) end
            line(tr('RecoverReport'))
        elseif signal then
            if row.mapZone then line(tr('SignalMapZone')) end
            line(tr('SignalColor', getText('IGUI_RS_SignalColor_' .. tostring(row.color))))
            line(tr('SignalHour', row.hour, (row.hour + row.windowHours) % 24))
            line(row.lit and tr('SignalLit', row.litBy) or tr('SignalNotLit'))
            line(tr('SignalRule')); line(tr('SignalReport'))
        elseif clear then
            if row.mapZone then line(tr('ClearMapZone')) end
            line(tr('ClearProgress', row.kills, row.target))
            for _, part in ipairs(type(row.tally) == 'table' and row.tally or {}) do
                line('- ' .. tr('ClearBy', part.name, part.count))
            end
            line(tr('ClearRule')); line(tr('ClearReport'))
        elseif retrieve then
            if row.mapZone and not row.found then line(tr('RetrieveMapZone')) end
            if row.person and row.person ~= '' then line(tr('RetrievePerson', row.person)) end
            line(row.found and tr('RetrieveFound', row.foundBy) or tr('RetrieveNotFound'))
            line(tr('RetrieveReport'))
        elseif scout then
            -- E11-T10: approximate area drawn on the world map (missions created since).
            if row.mapZone and not row.zoneReached then line(tr('ScoutMapZone')) end
            if voice then
                line(row.zoneReached and tr('ScoutReachedRadio', row.reachedBy) or tr('ScoutNotReached'))
                line(tr('ScoutReportRadio'))
            else
                line(row.zoneReached and tr('ScoutReached', row.reachedBy) or tr('ScoutNotReached')); line(tr('ScoutReport'))
            end
        elseif row.unit == 'value' then
            -- E17-T03: supply offer of a Living Knox group, counted in value points (one item = its value).
            line(tr('SupplyProgress', row.delivered, row.quantity))
            local accepted = {}
            for fullType in pairs(row.accepted) do
                accepted[#accepted + 1] = itemName(fullType) .. ' (' .. tostring((row.values or {})[fullType] or 0) .. ')'
            end
            table.sort(accepted)
            line(tr('AcceptedItems', table.concat(accepted, ', ')))
            line(tr('SupplyValues'))
        else
            line(tr('Progress', row.delivered, row.quantity))
            local accepted = {}
            for fullType in pairs(row.accepted) do accepted[#accepted + 1] = itemName(fullType) end
            table.sort(accepted)
            line(tr('AcceptedItems', table.concat(accepted, ', ')))
            line(tr('OneUnit'))
        end
        line(tr('Time', math.ceil(row.remainingMs / 60000)))
        if row.rewardCount > 0 then line(tr('Reward', row.rewardCount, itemName(row.rewardType)))
        elseif row.unit == 'value' then line(tr('RewardGoodwill'))
        else line(tr('RewardInformation')) end
        line(tr('Participants', table.concat(row.participants, ', ')))
        if row.toReport then line(row.donor == 'voice' and tr('ReportRadio', row.requester)
            or tr('ReportInPerson', row.requester)) end
        if not scout and not clear and not recover and not signal then line(tr('NoRefund')) end
        if row.claimedName ~= '' then line(tr('ClaimedBy', row.claimedName)) end
        if row.recovery then line(tr('Error_Recovery')) end
        if not row.near and not voice then line(tr('JoinRequester')) end
        self.accept:setVisible(row.invited and not row.engaged and (row.state == 'offer' or row.state == 'active'))
        enable(self.accept, not row.recovery)
        self.deliver:setVisible(row.engaged and row.state == 'active' and not scout and not clear and not recover
            and not signal)
        enable(self.deliver, row.near and not row.recovery)
        self.report:setVisible(row.engaged and row.state == 'active' and row.toReport == true and not voice)
        enable(self.report, row.near and not row.recovery)
        self.claim:setVisible(row.engaged and row.state == 'success' and row.rewardCount > 0)
        enable(self.claim, row.near and row.claimedName == '' and not row.recovery)
        self.abandon:setVisible(row.engaged and row.state == 'active')
        enable(self.abandon, not row.recovery)
        if row.engaged and row.state == 'active' and not voice then
            self.invite:setVisible(true); enable(self.invite, row.near and #(Client.snapshot.inviteTargets or {}) > 0)
            local selected = self.inviteTargets and self.inviteTargets[self.inviteChoice.selected]
            self.inviteTargets = Client.snapshot.inviteTargets or {}
            self.inviteChoice:clear()
            for i, target in ipairs(self.inviteTargets) do
                self.inviteChoice:addOption(target.name)
                if selected and target.id == selected.id then self.inviteChoice.selected = i end
            end
            self.inviteChoice:setVisible(true)
        end
    elseif radio and row then
        self:showRadio(row, text)
        return
    elseif self.tab == 'Team' then
        self:showTeam(row, line)
    elseif self.tab == 'Reputation' then
        for _, s in ipairs(Notebook.reputationLines(Client.snapshot.reputation, Client.snapshot.contacts)) do line(s) end
        if Notebook.canSeeAllReputations() then
            self.repAdmin:setVisible(true)
            for _, s in ipairs(Notebook.reputationAdminLines(Client.repAdmin)) do line(s) end
        end
    else line(tr('Empty_' .. self.tab)) end
    self.detail:setText(INK_TAG .. table.concat(text, ' <LINE> <LINE> '))
    self.radioShown = nil
    self:layout()
end

-- Team tab (E09-T03): faction or lone team, own role, mandates; the owner designates or withdraws a negotiator.
function Notebook:showTeam(row, line)
    local team = Client.snapshot.team
    if not team then line(tr('Empty_Team')); return end
    line(team.kind == 'faction' and tr('TeamFaction', team.name) or tr('TeamPersonal'))
    line(tr('TeamYou_' .. tostring(team.role)))
    line(tr('TeamRule'))
    if team.kind ~= 'faction' then return end
    line(tr('TeamMandates', team.negotiators, team.maxNegotiators))
    if not row then return end
    line(tr('TeamMember', row.name, tr('Role_' .. tostring(row.role))))
    if team.isOwner and row.role ~= 'owner' then
        local negotiator = row.role == 'negotiator'
        self.grant:setVisible(not negotiator); self.revoke:setVisible(negotiator)
        enable(self.grant, team.negotiators < team.maxNegotiators)
    end
end

-- Conversation of one frequency, oldest first; scrolled to the newest line when it changes. Reading it puts out the
-- global indicator and the dot of this frequency.
function Notebook:showRadio(row, text)
    local parts = {}
    for _, s in ipairs(text) do parts[#parts + 1] = INK_TAG .. s end
    local lines = History.lines(row.khz)
    for _, l in ipairs(lines) do
        local kind = RADIO_COLORS[l.kind] and l.kind or 'heard'
        -- Mission received (E11-T08): the line holds the kind of place, translated here.
        local said = kind == 'mission' and placeName(l.text) or l.text
        parts[#parts + 1] = '<RGB:' .. RADIO_COLORS[kind] .. '> ' .. clean(tr('Radio_' .. kind, l.when, said))
    end
    if #lines == 0 then parts[#parts + 1] = INK_TAG .. clean(tr('Empty_Radio')) end
    self.tune:setVisible(true)
    self.detail:setText(table.concat(parts, ' <LINE> '))
    if self:viewingRadio() then
        History.markRead()
        History.markFrequencyRead(row.khz)
        row.unread = false
    end
    self:layout()
    local last = lines[#lines]
    local shown = tostring(row.khz) .. '#' .. #lines .. '#' .. tostring(last and last.seq)
    if shown ~= self.radioShown and self.detail.setYScroll then self.detail:setYScroll(-100000) end
    self.radioShown = shown
end

-- Sends the Say line through the shared path (Talk.send: same checks, waiting and delay as the radio window),
-- then gives the keyboard back to the game.
function Notebook:sendSay()
    local player = getSpecificPlayer(0)
    local text = self.say:getText()
    if Talk.cleanText(text) ~= '' and Talk.send(player, talkDevice(player), text) then self.say:setText('') end
    self:releaseFocus()
end

-- Say line of the Contacts tab (E17-T06): sentence to the selected NPC through Client.talk (same command and server
-- checks as the local chat); said aloud once the server queued it. Then gives the keyboard back to the game.
function Notebook:sendTalk()
    local text = Talk.cleanText(self.speak:getText())
    if text ~= '' and Client.talkProblem(self.row) == nil and Client.talk(text, true) then self.speak:setText('') end
    self:releaseFocus()
end

-- State of the Contacts Say line, read each frame on that tab: greyed with the reason (no target, out of range,
-- dead, answer awaited, delay between two sentences); placeholder naming the contact.
function Notebook:syncTalk()
    local row = self.row
    local reason, problem = Client.talkProblem(row)
    local editable = reason == nil
    if self.speakEditable ~= editable then
        self.speakEditable = editable
        self.speak:setEditable(editable)
        enable(self.speakSend, editable)
        if not editable then self:releaseFocus(self.speak) end
    end
    local name = row and row.name or ''
    if name ~= self.speakName then
        self.speakName = name
        self.speak:setPlaceholderText(name ~= '' and tr('TalkPlaceholder', name) or '')
    end
    self.talkStatus, self.talkIsProblem = reason and tr(reason) or nil, problem == true
end

-- State of the Say line, read each frame on the Radio tab: greyed with the reason while waiting for an answer or
-- during the delay between two sentences; placeholder on the frequency of the radio; reason a sentence would be
-- refused, or a hint when the radio is on another frequency than the selected one.
function Notebook:syncSay()
    local now = getTimestampMs()
    if not self.deviceAt or now - self.deviceAt >= DEVICE_CACHE_MS then
        self.rsPlayer = getSpecificPlayer(0)
        self.rsDevice, self.deviceAt = talkDevice(self.rsPlayer), now
    end
    local busy = Talk.busyReason()
    local editable = busy == nil
    if self.sayEditable ~= editable then
        self.sayEditable = editable
        self.say:setEditable(editable)
        enable(self.sendRadio, editable)
        if not editable then self:releaseFocus(self.say) end
    end
    local data = self.rsDevice and self.rsDevice:getDeviceData()
    local khz = data and data:getChannel() or (self.row and self.row.khz)
    if khz ~= self.sayKhz then
        self.sayKhz = khz
        self.say:setPlaceholderText(khz and getText('IGUI_RadioSurvivor_Talk', Const.frequencyLabel(khz)) or '')
    end
    local status, problem = busy, true
    if not status and self.rsPlayer then status = Talk.problem(self.rsPlayer, self.rsDevice) end
    if not status and data and self.row and khz ~= self.row.khz then
        status, problem = tr('RadioTunedElsewhere', Const.frequencyLabel(khz), Const.frequencyLabel(self.row.khz)), false
    end
    self.sayStatus, self.sayProblem = status, problem
end

function Notebook:update()
    if ISCollapsableWindow.update then ISCollapsableWindow.update(self) end
    if not self.say then return end
    if not self:isVisible() or self.isCollapsed then self:releaseFocus(); return end
    if self.tab == 'Contacts' then
        self:releaseFocus(self.say)
        if self.speak:isVisible() then self:syncTalk() else self:releaseFocus(self.speak) end
        return
    end
    if self.tab ~= 'Radio' then self:releaseFocus(self.say, self.speak); return end
    self:releaseFocus(self.speak)
    self:syncSay()
end

-- Positions of every child and of the drawn parts (self.geo), from the window size, the fonts and the labels.
function Notebook:layout()
    if not self.tabs then return end
    local th = self:titleBarHeight()
    local fh, fhM, fhL = fontHeight(), fontHeight(UIFont.Medium), fontHeight(UIFont.Large)
    local gap, bh = 10, fh + 14
    -- Bookmarks: the part outside the paper fits the longest label; the active one overlaps the paper more.
    local labelW = 0
    for _, tab in ipairs(self.tabs) do labelW = math.max(labelW, width(tab.rsLabel)) end
    local paperRight = self.width - (labelW + TAB_PAD * 2 + 2)
    local ty = th + 30
    for _, tab in ipairs(self.tabs) do
        tab.rsOver = tab.rsTab.name == self.tab and 14 or 6
        tab:setX(paperRight - tab.rsOver); tab:setY(ty)
        tab:setWidth(self.width - paperRight + tab.rsOver); tab:setHeight(bh)
        ty = ty + bh + 6
    end
    -- Columns: frequencies / contacts / missions on the left, dashed separator, detail on the right.
    -- Bottom margin above the invisible resize strip (ISResizeWidget across the whole bottom edge takes the clicks).
    local top, bottom = th + 14, self.height - math.max(14, self:resizeWidgetHeight() + 4)
    local left = BINDING_W + 14
    local inner = paperRight - left - 18
    local showList = self.tab ~= 'Reputation'
    local colW = 0
    if showList then
        -- A row keeps 10 px on each side, the unread dot and its gap (Notebook.drawRow), plus a few pixels:
        -- MeasureStringX counts the width of the last glyph instead of its advance (AngelCodeFont.java:290).
        -- E03-T02: also the header of the tab, the target footer and the second line of every row (drawn whole).
        local needed = math.max(width(tr('RadioFrequency', '999.9'), UIFont.Medium) + DOT + 36,
            width(tr('RadioLast', '00/00 00:00')) + 24, width(tr('RadioHeardList')) + 4, width(tr('RadioTune')) + 24,
            width(tr(self.tab)) + 4, width(tr('Target', tr('None'))) + 4)
        for _, item in ipairs(self.list.items) do
            needed = math.max(needed, width(Notebook.rowSecondLine(item.item)) + 24)
            if self.tab == 'Radio' then needed = math.max(needed, width(item.text, UIFont.Medium) + DOT + 36) end
        end
        colW = math.floor(math.min(math.max(needed, inner * 0.3), inner * 0.42))
    end
    local sepX = left + colW + 12
    local rightX = showList and sepX + 16 or left
    local rightW = paperRight - 18 - rightX
    local footerH = fh + 8
    local headerH = fh + 10
    local geo = {th = th, paperRight = paperRight, left = left, colW = colW, sepX = sepX, rightX = rightX,
        rightW = rightW, top = top, bottom = bottom, showList = showList, headerH = headerH,
        footerY = bottom - fh}
    self.geo = geo
    -- Left column.
    self.list:setVisible(showList)
    local listTop = top + headerH
    local listMax = bottom - footerH - listTop
    local listH = listMax
    if self.tab == 'Radio' then
        local rows = #self.list.items
        listH = math.max(self.list.itemheight, math.min(rows * self.list.itemheight, listMax - bh - gap))
    end
    self.list:setX(left); self.list:setY(listTop); self.list:setWidth(colW); self.list:setHeight(math.max(listH, 1))
    if self.tune:isVisible() then
        self.tune:setX(left); self.tune:setY(listTop + listH + gap)
        self.tune:setWidth(math.min(width(self.tune.title) + 24, colW)); self.tune:setHeight(bh)
    end
    -- Right column: title, then the text, then the tab's own controls at the bottom.
    local titleH = fhL + 10
    local detailTop = top + titleH
    if self.tab == 'Radio' then
        local entryH = fhM + 10
        local statusH = fh * 2 + 8
        local inputY = bottom - entryH
        local sayW = width(tr('RadioSay')) + 10
        local sendW = math.min(width(self.sendRadio.title) + 28, math.floor(rightW / 3))
        -- Narrow page (large font, long label): the "Say:" label gives way, the placeholder still says it.
        if rightW - sayW - sendW - 10 < 80 then sayW = 0 end
        geo.sayLabel = sayW > 0
        self.say:setX(rightX + sayW); self.say:setY(inputY)
        self.say:setWidth(rightW - sayW - sendW - 10); self.say:setHeight(entryH)
        self.sendRadio:setX(rightX + rightW - sendW); self.sendRadio:setY(inputY)
        self.sendRadio:setWidth(sendW); self.sendRadio:setHeight(entryH)
        geo.inputY, geo.entryH, geo.statusY = inputY, entryH, inputY - statusH
        self.detail:setX(rightX); self.detail:setY(detailTop); self.detail:setWidth(rightW)
        self.detail:setHeight(math.max(40, geo.statusY - 4 - detailTop)); self.detail:paginate()
    else
        local available = bottom - detailTop
        self.detail:setX(rightX); self.detail:setY(detailTop); self.detail:setWidth(rightW)
        local visible = {}
        for _, b in ipairs(self.actions) do if b:isVisible() then visible[#visible + 1] = b end end
        local rows, x = 1, 0
        for _, b in ipairs(visible) do
            local bw = math.min(width(b.title) + 24, rightW)
            if x > 0 and x + bw > rightW then rows, x = rows + 1, 0 end
            b:setWidth(bw); b:setHeight(bh); b:setX(rightX + x)
            b.rsRow = rows; x = x + bw + gap
        end
        if #visible == 0 then rows = 0 end
        local noteH = fh * NOTE_LINES + 10
        -- Contacts Say line (E17-T06): two status lines, then the entry and its button.
        local talkLine = self.speak:isVisible()
        local entryH, statusH = fhM + 10, fh * 2 + 8
        local extra = (self.note:isVisible() and noteH + gap or 0) + (self.inviteChoice:isVisible() and bh + gap or 0)
            + (talkLine and statusH + entryH + gap or 0)
        local textH = math.max(60, available - rows * (bh + gap) - extra)
        self.detail:setHeight(textH); self.detail:paginate()
        local y = detailTop + textH + gap
        if talkLine then
            local inputY = y + statusH
            local sayW = width(tr('RadioSay')) + 10
            local sendW = math.min(width(self.speakSend.title) + 28, math.floor(rightW / 3))
            if rightW - sayW - sendW - 10 < 80 then sayW = 0 end
            geo.sayLabel = sayW > 0
            self.speak:setX(rightX + sayW); self.speak:setY(inputY)
            self.speak:setWidth(rightW - sayW - sendW - 10); self.speak:setHeight(entryH)
            self.speakSend:setX(rightX + rightW - sendW); self.speakSend:setY(inputY)
            self.speakSend:setWidth(sendW); self.speakSend:setHeight(entryH)
            geo.inputY, geo.entryH, geo.statusY = inputY, entryH, y
            y = inputY + entryH + gap
        end
        if self.note:isVisible() then
            self.note:setX(rightX); self.note:setY(y); self.note:setWidth(rightW); self.note:setHeight(noteH)
            y = y + noteH + gap
        end
        if self.inviteChoice:isVisible() then
            self.inviteChoice:setX(rightX); self.inviteChoice:setY(y)
            self.inviteChoice:setWidth(rightW); self.inviteChoice:setHeight(bh)
            y = y + bh + gap
        end
        for _, b in ipairs(visible) do b:setY(y + (b.rsRow - 1) * (bh + gap)) end
    end
    geo.rulesTop, geo.rulesBottom = detailTop, self.detail.y + self.detail.height
    self.rsWidth, self.rsHeight, self.rsTab = self.width, self.height, self.tab
end

-- One row of the left list: label (frequency, contact, mission) in a large hand, second line below, selected row
-- framed, orange dot for a frequency with unread lines.
function Notebook.drawRow(list, y, item)
    local h = list.itemheight
    local row = item.item
    local selected = list.selected == item.index
    if selected then
        -- The frame stops before the thin scroll bar of the notebook when the list scrolls.
        local boxW = list.width - 2 - (overflows(list) and SCROLL_W + 2 or 0)
        local p, f = COLOR.paperLight, COLOR.frame
        list:drawRect(1, y + 2, boxW, h - 4, 1, p[1], p[2], p[3])
        list:drawRectBorder(1, y + 2, boxW, h - 4, 1, f[1], f[2], f[3])
    end
    local fhM = fontHeight(UIFont.Medium)
    local dotW = row.unread and DOT + 6 or 0
    local first = fit(item.text, list.width - 20 - dotW, UIFont.Medium)
    local c = selected and COLOR.blue or COLOR.ink
    list:drawText(first, 10, y + 6, c[1], c[2], c[3], 1, UIFont.Medium)
    if row.unread then
        drawDot(list, 10 + width(first, UIFont.Medium) + 6, y + 6 + math.floor((fhM - DOT) / 2), DOT, COLOR.orange)
    end
    local l = COLOR.label
    list:drawText(fit(Notebook.rowSecondLine(row), list.width - 20), 10, y + 8 + fhM, l[1], l[2], l[3], 1, UIFont.Small)
    return y + h
end

-- Second line of a row: last line heard (Radio), role (Team, E09-T03), state of a mission in a short word when the
-- full sentence is long (E03-T02: the sentence stays on the page), contact alive or dead.
function Notebook.rowSecondLine(row)
    if row.khz then return tr('RadioLast', row.when ~= '' and row.when or '-') end
    if row.role then return tr('Role_' .. row.role) end
    -- E11-T13: an active mission whose objective is met waits for its report.
    local state = row.state and (row.state == 'active' and row.toReport and 'toReport' or row.state)
    if state then return getTextOrNull('IGUI_RS_StateShort_' .. tostring(state)) or tr('State_' .. state) end
    return row.alive and tr('Contact') or tr('Dead')
end

-- A bookmark (instance prerender of its ISButton): tinted tab texture, cream label, Radio dot when unread.
function Notebook.drawBookmark(b)
    local active = b.target and b.target.tab == b.rsTab.name
    local c = b.rsTab.color
    local k = active and 1 or 0.8
    local tex = texture('tab')
    if tex then b:drawTextureScaled(tex, 0, 0, b.width, b.height, 1, c[1] * k, c[2] * k, c[3] * k)
    else b:drawRect(0, 0, b.width, b.height, 1, c[1] * k, c[2] * k, c[3] * k) end
    if b.mouseOver and not active then b:drawRect(0, 0, b.width, b.height, 0.12, 1, 1, 1) end
    local p = COLOR.paper
    local x = b.rsOver + TAB_PAD - 2
    b:drawText(b.rsLabel, x, math.floor((b.height - fontHeight()) / 2), p[1], p[2], p[3], 1, UIFont.Small)
    if b.rsTab.name == 'Radio' and History.unread and not active then
        drawDot(b, b.width - DOT - 3, 3, DOT - 2, COLOR.paperLight)
    end
end

-- Paper, binding, rings, separator, ruled lines, headers and status texts (drawn under the children).
function Notebook:drawPaper()
    local g = self.geo
    local th, h = g.th, self.height - g.th
    local paper = texture('paper')
    local p = COLOR.paper
    if paper then self:drawTextureTiled(paper, 0, th, g.paperRight, h, 1, 1, 1, 1)
    else self:drawRect(0, th, g.paperRight, h, 1, p[1], p[2], p[3]) end
    self:drawRect(g.paperRight - 3, th, 3, h, 0.18, 0, 0, 0)
    local binding = texture('binding')
    local b = COLOR.binding
    if binding then self:drawTextureTiled(binding, 0, th, BINDING_W, h, 1, 1, 1, 1)
    else self:drawRect(0, th, BINDING_W, h, 1, b[1], b[2], b[3]) end
    local ring = texture('ring')
    local count = math.max(3, math.floor(h / 90))
    local step = (h - 40) / (count - 1)
    for i = 0, count - 1 do
        local y = math.floor(th + 20 + i * step - RING / 2)
        if ring then self:drawTextureScaled(ring, (BINDING_W - RING) / 2, y, RING, RING, 1)
        else
            local c = COLOR.cover
            self:drawRect((BINDING_W - 10) / 2, y + 4, 10, 10, 1, c[1], c[2], c[3])
        end
    end
    -- Ruled lines on the right page, under the text.
    local r = COLOR.rule
    local ruleStep = fontHeight(self.tab == 'Radio' and UIFont.Medium or UIFont.Small) + 6
    local y = g.rulesTop + ruleStep
    while y < g.rulesBottom do
        self:drawRect(g.rightX, y, g.rightW, 1, 0.9, r[1], r[2], r[3])
        y = y + ruleStep
    end
    local l = COLOR.label
    if g.showList then
        local d = COLOR.dash
        y = g.top
        while y < g.bottom do
            self:drawRect(g.sepX, y, 2, 5, 1, d[1], d[2], d[3])
            y = y + 9
        end
        local header = self.tab == 'Radio' and tr('RadioHeardList') or tr(self.tab)
        self:drawText(fit(header, g.colW), g.left, g.top, l[1], l[2], l[3], 1, UIFont.Small)
    end
    -- Title of the right page: frequency (Radio, ink blue), selected contact or mission, or the tab name.
    local title = self.tab == 'Reputation' and tr('Reputation')
        or self.row and (self.tab == 'Radio' and tr('RadioFrequency', Const.frequencyLabel(self.row.khz))
            or self.list.items[self.list.selected] and self.list.items[self.list.selected].text) or nil
    if title then
        local c = self.tab == 'Radio' and COLOR.blue or COLOR.ink
        self:drawText(fit(title, g.rightW, UIFont.Large), g.rightX, g.top, c[1], c[2], c[3], 1, UIFont.Large)
    end
    -- Footer of the left column: target of the local chat (unchanged text).
    local selected = Client.snapshot.selected
    local name = ''
    for _, contact in ipairs(Client.snapshot.contacts or {}) do if contact.id == selected then name = contact.name end end
    local footerW = g.showList and g.colW or g.rightW
    self:drawText(fit(tr('Target', name ~= '' and name or tr('None')), footerW), g.left, g.footerY, l[1], l[2], l[3], 1,
        UIFont.Small)
    -- Say line of the Radio tab, or of the Contacts tab (E17-T06): label and status above it.
    if g.inputY and (self.tab == 'Radio' or self.tab == 'Contacts') then
        if g.sayLabel then
            local labelY = g.inputY + math.floor((g.entryH - fontHeight()) / 2)
            self:drawText(tr('RadioSay'), g.rightX, labelY, l[1], l[2], l[3], 1, UIFont.Small)
        end
        local status, problem = self.sayStatus, self.sayProblem
        if self.tab == 'Contacts' then status, problem = self.talkStatus, self.talkIsProblem end
        if status then
            local c = problem and COLOR.problem or COLOR.hint
            for i, text in ipairs(wrap(status, g.rightW, 2)) do
                self:drawText(text, g.rightX, g.statusY + (i - 1) * (fontHeight() + 2), c[1], c[2], c[3], 1, UIFont.Small)
            end
        end
    end
end

-- Thin paper scroll bar on the right edge of a list or text that does not fit (nil when it fits), in window
-- coordinates: track x, y, w, h, then the thumb (thumbY, thumbH) placed from the current scroll.
function Notebook:scrollBar(element)
    if not element:isVisible() or not overflows(element) then return nil end
    local h, total = element.height, element:getScrollHeight()
    local thumbH = math.min(h, math.max(16, math.floor(h * h / total)))
    local range = total - h
    local offset = math.min(math.max(-element:getYScroll(), 0), range)
    return {x = element.x + element.width - SCROLL_W, y = element.y, w = SCROLL_W, h = h, thumbH = thumbH,
        thumbY = element.y + math.floor((h - thumbH) * offset / range)}
end

function Notebook:drawScrollBars()
    local f, l = COLOR.frame, COLOR.label
    for _, element in ipairs({self.list, self.detail}) do
        local bar = self:scrollBar(element)
        if bar then
            self:drawRect(bar.x, bar.y, bar.w, bar.h, 0.3, f[1], f[2], f[3])
            self:drawRect(bar.x, bar.thumbY, bar.w, bar.thumbH, 0.9, l[1], l[2], l[3])
        end
    end
end

function Notebook:prerender()
    local th = self:titleBarHeight()
    local height = self.isCollapsed and th or self.height
    -- Discreet title bar: dark cover, title in cream; the close and collapse buttons stay (vanilla children).
    local c, p = COLOR.cover, COLOR.paper
    self:drawRect(0, 0, self.width, th, 0.96, c[1], c[2], c[3])
    if self.title then self:drawTextCentre(self.title, self.width / 2, 1, p[1], p[2], p[3], 1, UIFont.Small) end
    if History.unread then
        -- Indicator in the title bar, visible even when the notebook is collapsed.
        local w = math.max(6, math.floor(th / 2))
        drawDot(self, self.width - w - 46, math.floor((th - w) / 2), w, {0.95, 0.55, 0.1})
    end
    if self.clearStentil then self:setStencilRect(0, 0, self.width, height) end
    if self.isCollapsed then return end
    if self.rsWidth ~= self.width or self.rsHeight ~= self.height or self.rsTab ~= self.tab then self:layout() end
    self:drawPaper()
end

function Notebook:render()
    if self.clearStentil then self:clearStencilRect() end
    if self.isCollapsed then return end
    local g = self.geo
    local c = COLOR.cover
    if g then self:drawRectBorder(0, 0, g.paperRight, self.height, 1, c[1], c[2], c[3]) end
    self:drawScrollBars()
    if self.resizable and self.resizeWidget and self.resizeWidget:isVisible() and self.resizeimage then
        local rh = self:resizeWidgetHeight()
        self:drawTextureScaled(self.resizeimage, self.width - rh + 1, self.height - rh + 1, rh - 2, rh - 2, 1, 1, 1, 1)
    end
    if self.drawJoypadFocus then self:drawRectBorder(0, 0, self.width, self.height, 0.4, 0.2, 1.0, 1.0) end
end

local Delivery = ISCollapsableWindow:derive('RS_UI_Delivery')
local function inventoryItems(container, out, depth)
    if depth > 8 then return end
    local items = container:getItems()
    for i = 0, items:size() - 1 do
        local item = items:get(i)
        out[#out + 1] = item
        if instanceof(item, 'InventoryContainer') then inventoryItems(item:getItemContainer(), out, depth + 1) end
    end
end

function Delivery:createChildren()
    ISCollapsableWindow.createChildren(self)
    self.items = ISScrollingListBox:new(12, self:titleBarHeight() + 12, self.width - 24, self.height - self:titleBarHeight() - 95)
    self.items:initialise(); self:addChild(self.items)
    self.items.itemheight = fontHeight() + 12
    self.chosen = {}
    local all = {}
    inventoryItems(getSpecificPlayer(0):getInventory(), all, 0)
    for _, item in ipairs(all) do
        if self.mission.accepted[item:getFullType()] and item:getCondition() > 0 and not item:isFavorite() and not item:isEquipped() then
            self.items:addItem(item:getDisplayName(), {id = item:getID()})
        end
    end
    self.items:setOnMouseDownFunction(self, function(window, row)
        if window.chosen[row.id] then window.chosen[row.id] = nil
        else
            local count = 0
            for _ in pairs(window.chosen) do count = count + 1 end
            if count < window.mission.quantity - window.mission.delivered then window.chosen[row.id] = true end
        end
    end)
    -- E03-T07: item names cut to the row (ellipsis), room kept for the vanilla scroll bar (rows cut at vscroll.x + 3,
    -- ISScrollingListBox.lua:494-495).
    self.items.doDrawItem = function(list, y, item)
        local mark = list.parent.chosen[item.item.id] and '[x] ' or '[ ] '
        local room = list.width - 8 - 17 - 4 - width(mark)
        list:drawText(mark .. fit(item.text, room), 8, y + 4, 1, 1, 1, 1, UIFont.Small)
        return y + list.itemheight
    end
    self.prepare = button(self, tr('ReviewDelivery'), function(window)
        local ids = {}
        for id in pairs(window.chosen) do ids[#ids + 1] = id end
        table.sort(ids)
        if #ids > 0 then Client.send('prepare_delivery', {mission = window.mission.id, revision = window.mission.revision, items = ids}) end
    end)
    self.prepare:setX(12); self.prepare:setY(self.height - fontHeight() - 42)
end

-- Delivery window of a mission, created without being shown (read by the in-game suite rs.notebook.visual).
-- E03-T07: centred on the element anchor (the notebook), else on the screen, and always kept whole on the screen.
function Notebook.newDelivery(mission, anchor)
    local sw, sh = getCore():getScreenWidth(), getCore():getScreenHeight()
    local w, h = math.min(560, sw - 60), math.min(520, sh - 60)
    local x, y = (sw - w) / 2, (sh - h) / 2
    if anchor then
        x = anchor:getX() + (anchor:getWidth() - w) / 2
        y = anchor:getY() + (anchor:getHeight() - h) / 2
    end
    x = math.floor(math.max(0, math.min(x, sw - w)))
    y = math.floor(math.max(0, math.min(y, sh - h)))
    local window = Delivery:new(x, y, w, h)
    window.title, window.mission = tr('Delivery'), mission
    window:setResizable(false); window:initialise()
    return window
end

function Notebook:openDelivery(mission)
    local window = Notebook.newDelivery(mission, self)
    window:addToUIManager()
    Client.deliveryWindow = window
    return window
end

Client.confirmQuote = function(quote)
    if not Client.window then return end
    local text = tr('ConfirmDelivery', quote.count, quote.requester, quote.remaining)
    if quote.unit == 'value' then text = tr('ConfirmSupply', quote.count, quote.requester, quote.remaining, quote.value) end
    return Client.window:confirm(text, function()
        Client.send('confirm_delivery', {mission = quote.mission, revision = quote.revision, token = quote.token})
        if Client.deliveryWindow then Client.deliveryWindow:close() end
    end)
end

function Notebook.toggle()
    if not Client.window then Client.window = Notebook:new(); Client.window:initialise(); Client.window:addToUIManager()
    else
        if Client.window:isVisible() then Client.window:releaseFocus() end
        Client.window:setVisible(not Client.window:isVisible()); Client.window:bringToTop()
    end
    Client.send('snapshot')
    -- Lines received while the notebook was closed are read again on opening: ask the authority for the whole history.
    if Client.window:isVisible() then History.request() end
end

