local specs, byName = {}, {}

-- Active mod ids (getActivatedMods, LuaManager.java:6065: Java list, a leading "\" dropped). Absent outside the game
-- (offline benches): every mod counts as active.
function Notebook.modActive(id)
    if id == CORE_MOD or type(getActivatedMods) ~= 'function' then return true end
    local mods = getActivatedMods()
    for i = 0, (mods and mods:size() or 0) - 1 do
        if string.gsub(tostring(mods:get(i)), '^\\', '') == id then return true end
    end
    return false
end

function Notebook.registerTab(spec)
    if type(spec) ~= 'table' or type(spec.name) ~= 'string' then return nil end
    spec.mods = type(spec.mods) == 'table' and spec.mods or {}
    spec.order = tonumber(spec.order) or 100
    if not byName[spec.name] then specs[#specs + 1] = spec
    else
        for i, s in ipairs(specs) do if s.name == spec.name then specs[i] = spec end end
    end
    byName[spec.name] = spec
    table.sort(specs, function(a, b) return a.order < b.order end)
    return spec
end

-- A mod fills a tab registered by another (a common tab): its fields replace the defaults.
function Notebook.extendTab(name, fields)
    local spec = byName[name]
    if not spec or type(fields) ~= 'table' then return nil end
    for k, v in pairs(fields) do spec[k] = v end
    return spec
end

function Notebook.tabSpec(name) return byName[name] end

-- Tabs shown in this game, in their order: the mods each one names are all active.
function Notebook.shownTabs()
    local out = {}
    for _, spec in ipairs(specs) do
        local ok = true
        for _, id in ipairs(spec.mods) do if not Notebook.modActive(id) then ok = false end end
        if ok then out[#out + 1] = spec end
    end
    return out
end

function Notebook.tabLabel(spec)
    if type(spec.label) == 'function' then return spec.label() end
    return tr(spec.name)
end

-- Something unread on a shown tab (dot on the bookmark, in the title bar and on the sidebar button).
function Notebook.anyUnread()
    for _, spec in ipairs(Notebook.shownTabs()) do
        if spec.unread and spec.unread() then return true end
    end
    return false
end

