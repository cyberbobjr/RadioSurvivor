-- "Stamp" button of the notebook: ink border and text on the paper; filled in ink for the main action.
local function stamp(parent, label, action, filled)
    local b = ISButton:new(0, 0, width(label) + 24, fontHeight() + 14, label, parent, action)
    b:initialise(); parent:addChild(b)
    local c = COLOR.rust
    b.rsFilled = filled == true
    b.borderColor = rgb(c)
    if b.rsFilled then
        b.backgroundColor = rgb(c)
        b.backgroundColorMouseOver = {r = 0.6, g = 0.3, b = 0.1, a = 1}
        b.textColor = rgb(COLOR.paper)
    else
        b.backgroundColor = {r = c[1], g = c[2], b = c[3], a = 0}
        b.backgroundColorMouseOver = {r = c[1], g = c[2], b = c[3], a = 0.14}
        b.textColor = rgb(c)
    end
    return b
end

-- Enabled state of a stamp without ISButton:setEnable, which paints a disabled button black (ISButton.lua:416-438).
-- A disabled button ignores clicks (ISButton.lua:45, 60) and draws its title in grey (ISButton.lua:251-257).
local function enable(b, on)
    b.enable = on and true or false
    b.borderColor.a = b.enable and 1 or 0.35
    if b.rsFilled then b.backgroundColor.a = b.enable and 1 or 0.35 end
end

-- Text entry drawn on the paper: underlined (say line) or a light box (private note). Ink text colour is set on the
-- Java object, after addChild (base ui-windows.md, ISTextEntryBox).
local function paperEntry(entry, underline)
    entry.prerender = function(e)
        if underline then
            local c = COLOR.rust
            local a = (e.javaObject and e:isEditable()) and 1 or 0.35
            e:drawRect(0, e.height - 2, e.width, 2, a, c[1], c[2], c[3])
        else
            local p, f = COLOR.paperLight, COLOR.frame
            e:drawRect(0, 0, e.width, e.height, 0.85, p[1], p[2], p[3])
            e:drawRectBorder(0, 0, e.width, e.height, 1, f[1], f[2], f[3])
        end
    end
    local i = COLOR.ink
    entry:setTextRGBA(i[1], i[2], i[3], 1)
end

local function drawDot(element, x, y, size, c)
    local tex = texture('dot')
    if tex then element:drawTextureScaled(tex, x, y, size, size, 1, c[1], c[2], c[3])
    else element:drawRect(x, y, size, size, 1, c[1], c[2], c[3]) end
end

