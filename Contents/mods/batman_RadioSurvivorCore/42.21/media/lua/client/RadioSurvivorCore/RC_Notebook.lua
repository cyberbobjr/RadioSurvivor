function Notebook:new()
    local sw, sh = getCore():getScreenWidth(), getCore():getScreenHeight()
    local w, h = math.min(sw - 80, math.max(780, fontHeight() * 46)), math.min(sh - 70, 760)
    local o = ISCollapsableWindow.new(self, (sw - w) / 2, (sh - h) / 2, w, h)
    o.title = tr('Notebook')
    local shown = Notebook.shownTabs()
    o.tab = byName.Contacts and 'Contacts' or (shown[1] and shown[1].name)
    -- Minimum size grows with the font size option (E03-T02): at 480 px a larger font pushed the Contacts buttons
    -- out of the window, at 660 px the left column cut its labels. Unchanged with the smallest fonts (19 px).
    o.minimumWidth = math.min(math.max(660, fontHeight() * 34), sw - 80)
    o.minimumHeight = math.min(math.max(480, fontHeight() * 25), sh - 70)
    o.resizable = true
    o.playerNum = 0
    o.borderColor = {r = 0.17, g = 0.16, b = 0.15, a = 1}
    return o
end

