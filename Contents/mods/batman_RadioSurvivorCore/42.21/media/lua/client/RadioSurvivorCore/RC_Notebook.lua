-- Keyboard focus back to the game (an ISTextEntryBox keeps it until unfocus or the next left click, even hidden).
-- Without argument: every text entry of the notebook; otherwise only the entries given.
function Notebook:releaseFocus(...)
    local entries = {...}
    if #entries == 0 then
        for _, e in ipairs(self.entries or {}) do entries[#entries + 1] = e.entry end
    end
    for _, entry in ipairs(entries) do
        if entry and entry.javaObject and entry:isFocused() then entry:unfocus() end
    end
end

function Notebook:close()
    self:releaseFocus()
    ISCollapsableWindow.close(self)
    local joypad = JoypadState and JoypadState.players[self.playerNum + 1]
    if joypad and joypad.focus == self then setJoypadFocus(self.playerNum, nil) end
end

function Notebook:changeTab(name)
    if not byName[name] then return end
    self:releaseFocus()
    self.tab, self.selectedId = name, nil
    local spec = self:spec()
    if spec.onOpen then spec.onOpen(self) end
    self:refresh()
end

-- Is the player reading this tab right now (visible, expanded)?
function Notebook:viewing(name)
    return self.tab == name and self:isVisible() and not self.isCollapsed
end

function Notebook:refresh()
    if not self.list then return end
    local spec = self:spec()
    local old = self.selectedId
    self.list:clear()
    local rows = spec.rows and spec.rows(self) or {}
    for i, row in ipairs(rows) do
        self.list:addItem(spec.rowLabel and spec.rowLabel(row) or tostring(row.name or row.id), row)
        if row.id == old then self.list.selected = i end
    end
    if not old and rows[1] then self.selectedId, self.list.selected = rows[1].id, 1 end
    self:showDetail()
end

function Notebook:showDetail()
    local row
    for _, item in ipairs(self.list.items) do if item.item.id == self.selectedId then row = item.item end end
    self.row = row
    for _, b in ipairs(self.actions) do b:setVisible(false) end
    for _, e in ipairs(self.owned) do e:setVisible(false) end
    local spec = self:spec()
    self.detail.defaultFont = spec.font or UIFont.Small
    local text = {}
    local function line(s) text[#text + 1] = clean(s) end
    for _, notice in ipairs(Notebook.notices) do notice(self, self.tab, line) end
    if spec.detail then
        if spec.detail(self, row, line, text) then return end
    else
        line(spec.empty and spec.empty() or tr('Empty_' .. tostring(self.tab)))
    end
    self.detail:setText(INK_TAG .. table.concat(text, ' <LINE> <LINE> '))
    self.scrollKey = nil
    self:layout()
end

function Notebook:update()
    if ISCollapsableWindow.update then ISCollapsableWindow.update(self) end
    if not self.list then return end
    if not self:isVisible() or self.isCollapsed then self:releaseFocus(); return end
    for _, e in ipairs(self.entries) do
        if e.tab ~= self.tab then self:releaseFocus(e.entry) end
    end
    local spec = self:spec()
    if spec.update then spec.update(self) end
end

-- Width of the left column: the widest of its header, footer, rows and of what the mods ask on every tab.
function Notebook:columnNeeded(spec)
    local needed = width(spec.header and spec.header(self) or Notebook.tabLabel(spec)) + 4
    for _, fn in ipairs(Notebook.columnWidths) do needed = math.max(needed, fn(self) or 0) end
    for _, item in ipairs(self.list.items) do
        needed = math.max(needed, width(Notebook.rowSecondLine(item.item, spec)) + 24)
        if spec.wideRows then needed = math.max(needed, width(item.text, UIFont.Medium) + DOT + 36) end
    end
    return needed
end

-- Say line of a block: entry and button on one row, the "Say:" label before them while the page is wide enough.
local function placeSayLine(block, geo, inputY, entryH)
    local rightX, rightW = geo.rightX, geo.rightW
    local sayW = block.label and width(block.label) + 10 or 0
    local sendW = math.min(width(block.send.title) + 28, math.floor(rightW / 3))
    -- Narrow page (large font, long label): the "Say:" label gives way, the placeholder still says it.
    if rightW - sayW - sendW - 10 < 80 then sayW = 0 end
    geo.sayLabel = sayW > 0 and block.label or nil
    block.entry:setX(rightX + sayW); block.entry:setY(inputY)
    block.entry:setWidth(rightW - sayW - sendW - 10); block.entry:setHeight(entryH)
    block.send:setX(rightX + rightW - sendW); block.send:setY(inputY)
    block.send:setWidth(sendW); block.send:setHeight(entryH)
end
Notebook.placeSayLine = placeSayLine

-- Positions of every child and of the drawn parts (self.geo), from the window size, the fonts and the labels.
function Notebook:layout()
    if not self.tabs then return end
    local spec = self:spec()
    local th = self:titleBarHeight()
    local fh, fhM, fhL = fontHeight(), fontHeight(UIFont.Medium), fontHeight(UIFont.Large)
    local gap, bh = 10, fh + 14
    -- Bookmarks: the part outside the paper fits the longest label; the active one overlaps the paper more.
    local labelW = 0
    for _, tab in ipairs(self.tabs) do labelW = math.max(labelW, width(tab.rsLabel)) end
    local paperRight = self.width - (labelW + TAB_PAD * 2 + 2)
    local ty = th + 30
    for _, tab in ipairs(self.tabs) do
        tab.rsOver = tab.rsTab.name == self.tab and 14 or 6
        tab:setX(paperRight - tab.rsOver); tab:setY(ty)
        tab:setWidth(self.width - paperRight + tab.rsOver); tab:setHeight(bh)
        ty = ty + bh + 6
    end
    -- Columns: rows on the left, dashed separator, page on the right.
    -- Bottom margin above the invisible resize strip (ISResizeWidget across the whole bottom edge takes the clicks).
    local top, bottom = th + 14, self.height - math.max(14, self:resizeWidgetHeight() + 4)
    local left = BINDING_W + 14
    local inner = paperRight - left - 18
    local showList = spec.showList ~= false
    local colW = 0
    if showList then
        colW = math.floor(math.min(math.max(self:columnNeeded(spec), inner * 0.3), inner * 0.42))
    end
    local sepX = left + colW + 12
    local rightX = showList and sepX + 16 or left
    local rightW = paperRight - 18 - rightX
    local footerH = fh + 8
    local headerH = fh + 10
    local titleH = fhL + 10
    local geo = {th = th, paperRight = paperRight, left = left, colW = colW, sepX = sepX, rightX = rightX,
        rightW = rightW, top = top, bottom = bottom, showList = showList, headerH = headerH,
        footerY = bottom - fh, gap = gap, bh = bh, detailTop = top + titleH}
    self.geo = geo
    -- Left column.
    self.list:setVisible(showList)
    local listTop = top + headerH
    local listMax = bottom - footerH - listTop
    local listH = spec.listHeight and spec.listHeight(self, listMax, bh, gap) or listMax
    self.list:setX(left); self.list:setY(listTop); self.list:setWidth(colW); self.list:setHeight(math.max(listH, 1))
    if spec.layoutLeft then spec.layoutLeft(self, geo, listTop, listH) end
    -- Right column: title, then the text, then the tab's own controls at the bottom.
    local detailTop = geo.detailTop
    if spec.layout then
        spec.layout(self, geo)
    else
        local available = bottom - detailTop
        self.detail:setX(rightX); self.detail:setY(detailTop); self.detail:setWidth(rightW)
        local visible = {}
        for _, b in ipairs(self.actions) do if b:isVisible() then visible[#visible + 1] = b end end
        local rows, x = 1, 0
        for _, b in ipairs(visible) do
            local bw = math.min(width(b.title) + 24, rightW)
            if x > 0 and x + bw > rightW then rows, x = rows + 1, 0 end
            b:setWidth(bw); b:setHeight(bh); b:setX(rightX + x)
            b.rsRow = rows; x = x + bw + gap
        end
        if #visible == 0 then rows = 0 end
        -- Blocks between the text and the buttons: a say line (two status lines, then the entry and its button) or
        -- an element of its own height.
        local entryH, statusH = fhM + 10, fh * 2 + 8
        local blocks, extra = {}, 0
        for _, block in ipairs(self.blocks) do
            if block.entry and block.entry:isVisible() then
                blocks[#blocks + 1] = block; extra = extra + statusH + entryH + gap
            elseif block.element and block.element:isVisible() then
                blocks[#blocks + 1] = block; extra = extra + block.height + gap
            end
        end
        local textH = math.max(60, available - rows * (bh + gap) - extra)
        self.detail:setHeight(textH); self.detail:paginate()
        local y = detailTop + textH + gap
        for _, block in ipairs(blocks) do
            if block.entry then
                local inputY = y + statusH
                placeSayLine(block, geo, inputY, entryH)
                geo.inputY, geo.entryH, geo.statusY = inputY, entryH, y
                y = inputY + entryH + gap
            else
                local e = block.element
                e:setX(rightX); e:setY(y); e:setWidth(rightW); e:setHeight(block.height)
                y = y + block.height + gap
            end
        end
        for _, b in ipairs(visible) do b:setY(y + (b.rsRow - 1) * (bh + gap)) end
    end
    geo.rulesTop, geo.rulesBottom = detailTop, self.detail.y + self.detail.height
    self.rsWidth, self.rsHeight, self.rsTab = self.width, self.height, self.tab
end

-- One row of the left list: label in a large hand, second line below, selected row framed, orange dot when unread.
function Notebook.drawRow(list, y, item)
    local h = list.itemheight
    local row = item.item
    local selected = list.selected == item.index
    if selected then
        -- The frame stops before the thin scroll bar of the notebook when the list scrolls.
        local boxW = list.width - 2 - (overflows(list) and SCROLL_W + 2 or 0)
        local p, f = COLOR.paperLight, COLOR.frame
        list:drawRect(1, y + 2, boxW, h - 4, 1, p[1], p[2], p[3])
        list:drawRectBorder(1, y + 2, boxW, h - 4, 1, f[1], f[2], f[3])
    end
    local fhM = fontHeight(UIFont.Medium)
    local dotW = row.unread and DOT + 6 or 0
    local first = fit(item.text, list.width - 20 - dotW, UIFont.Medium)
    local c = selected and COLOR.blue or COLOR.ink
    list:drawText(first, 10, y + 6, c[1], c[2], c[3], 1, UIFont.Medium)
    if row.unread then
        drawDot(list, 10 + width(first, UIFont.Medium) + 6, y + 6 + math.floor((fhM - DOT) / 2), DOT, COLOR.orange)
    end
    local l = COLOR.label
    local window = list.rcWindow
    local spec = window and window:spec() or nil
    list:drawText(fit(Notebook.rowSecondLine(row, spec), list.width - 20), 10, y + 8 + fhM, l[1], l[2], l[3], 1,
        UIFont.Small)
    return y + h
end

