-- Native sidebar button, appended after vanilla buttons without replacing its option dispatch.
local function sidebar(panel)
    if panel.rcNotebook or panel.playerNum ~= 0 then return end
    panel.rcNotebook = button(panel, tr('Notebook'), function() Notebook.toggle(0, false) end)
    panel.rcNotebook:setX(0)
    panel.rcNotebook:setY(panel.height + 8)
    local hints = {tr('NotebookHint')}
    for _, key in ipairs(Notebook.hints) do hints[#hints + 1] = getText(key) end
    panel.rcNotebook.tooltip = table.concat(hints, ' <LINE> ')
    -- Reception indicator: something new while the notebook was closed, collapsed or on another tab.
    local baseRender = panel.rcNotebook.render
    panel.rcNotebook.render = function(b, ...)
        if baseRender then baseRender(b, ...) end
        if Notebook.anyUnread() then b:drawRect(b.width - 9, 3, 6, 6, 1, 0.95, 0.55, 0.1) end
    end
    panel:shrinkWrap()
end

local previousSidebar = ISEquippedItem.initialise
ISEquippedItem.initialise = function(self, ...)
    local result = previousSidebar(self, ...)
    sidebar(self)
    return result
end

local previousWheel = ISDPadWheels.onDisplayRight
function ISDPadWheels.onDisplayRight(joypadData, ...)
    local result = previousWheel(joypadData, ...)
    local menu = getPlayerRadialMenu(joypadData.player)
