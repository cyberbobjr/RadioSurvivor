-- Text cut to a width (ellipsis); results cached, the same labels are drawn every frame.
local fitCache, fitCount = {}, 0
local function fit(text, maxWidth, font)
    text = tostring(text or '')
    font = font or UIFont.Small
    maxWidth = math.floor(maxWidth)
    if maxWidth <= 0 then return '' end
    local key = tostring(font) .. '|' .. maxWidth .. '|' .. text
    local cached = fitCache[key]
    if cached then return cached end
    local out = text
    if width(text, font) > maxWidth then
        local n = string.len(text)
        while n > 0 and width(string.sub(text, 1, n) .. '...', font) > maxWidth do n = n - 1 end
        out = string.sub(text, 1, n) .. '...'
    end
    if fitCount > 400 then fitCache, fitCount = {}, 0 end
    fitCache[key], fitCount = out, fitCount + 1
    return out
end

-- Words wrapped to a width, at most maxLines lines (the last one cut with an ellipsis).
local function wrap(text, maxWidth, maxLines, font)
    local lines, current = {}, ''
    for word in string.gmatch(tostring(text or ''), '%S+') do
        local candidate = current == '' and word or current .. ' ' .. word
        if current ~= '' and width(candidate, font) > maxWidth then
            lines[#lines + 1] = current
            current = word
        else
            current = candidate
        end
    end
    if current ~= '' then lines[#lines + 1] = current end
    if #lines > maxLines then
        local last = {}
        for i = maxLines, #lines do last[#last + 1] = lines[i] end
        for i = #lines, maxLines, -1 do lines[i] = nil end
        lines[maxLines] = table.concat(last, ' ')
    end
    for i, line in ipairs(lines) do lines[i] = fit(line, maxWidth, font) end
    return lines
end

local function rgb(c) return {r = c[1], g = c[2], b = c[3], a = 1} end

-- No vanilla scroll bar on the paper. An ISScrollBar takes its place from the size of its parent when it is created
-- (ISScrollBar.lua:268-297: x = parent.width - 16) and then only follows it through the Java anchors, whose size
-- difference is lost when the size is set twice before the next update (UIElement.java:1419-1425, 1463-1469,
-- 1132-1147): the notebook lays out several times per frame, the bar stayed at x = 84 in the middle of the panel and
-- the list cut its rows there (ISScrollingListBox.lua:494-495). The wheel scrolls without it (ISScrollingListBox.lua:347,
-- ISRichTextPanel.lua:400, ISUIElement.lua:1701-1716 clamps); Notebook:render draws a thin bar on the right edge.
local function withoutScrollBar(element)
    if element.vscroll then element:removeScrollBars() end
    element.vscroll = nil
end

-- Content taller than the element (set by ISScrollingListBox:prerender and ISRichTextPanel:paginate).
local function overflows(element)
